/*
 * tests/demo.c —— elfcfg 的测试目标程序
 *
 * 编译（不要优化，否则控制流会被合并）：
 *     gcc -O0 -fno-pie -no-pie tests/demo.c -o demo
 *
 * 包含不同复杂度的函数，便于课堂按需选择：
 *     simple_if   —— 最简单的单条件分支
 *     nested_if   —— 嵌套条件
 *     loop_sum    —— for + while 循环
 *     classify    —— 多分支 + 循环（课堂主用）
 *     switch_test —— switch（GCC 会生成跳转表，用于演示已知限制）
 *     call_test   —— 函数调用
 *     main        —— 调用上述函数
 */

#include <stdio.h>
#include <stdlib.h>

/* ---------------------------------------------------------------------------
 * 1. 最简单的条件分支：CFG 只有 3 个基本块
 * ------------------------------------------------------------------------- */
int simple_if(int x)
{
    if (x > 0) {
        return x + 1;
    }
    return 0;
}

/* ---------------------------------------------------------------------------
 * 2. 嵌套条件：形成多层分叉与汇合
 * ------------------------------------------------------------------------- */
int nested_if(int x)
{
    int r = 0;

    if (x > 100) {
        if (x > 1000) {
            r = 3;
        } else {
            r = 2;
        }
    } else {
        if (x > 0) {
            r = 1;
        }
    }
    return r;
}

/* ---------------------------------------------------------------------------
 * 3. 循环：for + while，CFG 中会出现两条向后跳转边
 * ------------------------------------------------------------------------- */
int loop_sum(int n)
{
    int sum = 0;
    int i;

    for (i = 0; i < n; i++) {
        sum += i;
    }

    while (sum > 100) {
        sum -= 10;
    }

    return sum;
}

/* ---------------------------------------------------------------------------
 * 4. 多分支 + 循环（课堂演示主用例）
 * ------------------------------------------------------------------------- */
int classify(int x)
{
    int sum = 0;
    int i;

    if (x > 100) {              /* 分支 1：x > 100        */
        sum = 100;
    } else if (x > 0) {         /* 分支 2：0 < x <= 100   */
        sum = x;
    } else {                    /* 分支 3：x <= 0         */
        sum = -x;
    }

    for (i = 0; i < 3; i++) {   /* for 循环：形成向后跳转边 */
        sum = sum + i;
    }

    return sum;
}

/* ---------------------------------------------------------------------------
 * 5. switch：GCC 在 -O0 下也会为较多分支生成跳转表
 *    用于演示"间接跳转无法静态解析"这一已知限制
 * ------------------------------------------------------------------------- */
int switch_test(int x)
{
    switch (x) {
    case 0:  return 10;
    case 1:  return 20;
    case 2:  return 30;
    case 3:  return 40;
    case 4:  return 50;
    default: return -1;
    }
}

/* ---------------------------------------------------------------------------
 * 6. 函数调用：用于观察 call 指令的处理
 * ------------------------------------------------------------------------- */
int call_test(int x)
{
    int a = simple_if(x);
    int b = nested_if(x);
    return a + b + loop_sum(x);
}

/* ---------------------------------------------------------------------------
 * 主函数
 * ------------------------------------------------------------------------- */
int main(int argc, char **argv)
{
    int v = 42;

    if (argc > 1) {
        v = atoi(argv[1]);
    }

    printf("simple_if(%d)   = %d\n", v, simple_if(v));
    printf("nested_if(%d)   = %d\n", v, nested_if(v));
    printf("loop_sum(%d)    = %d\n", v, loop_sum(v));
    printf("classify(%d)    = %d\n", v, classify(v));
    printf("switch_test(%d) = %d\n", v, switch_test(v));
    printf("call_test(%d)   = %d\n", v, call_test(v));
    return 0;
}
